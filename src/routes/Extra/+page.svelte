<h1>About</h1>
<main class="grid-Main">
	<section class="double-Block">
		<p>
			The first recorded Kitsap County Fair was held in 1923 in Port Orchard. It moved to Bremerton,
			in 1958. In 1929, exhibitors at the Fair totaled 1,000; today there are more than 6,000, with
			an annual attendance of over 80,000.
		</p>
		<p>
			In 1960, the Chief Kitsap Stampede sold stock certificates for $1 and constructed the
			Thunderbird Arena. When completed, it held 12,000 spectators. In the late ‘70’s, portions of
			the Arena were condemned. The covered grandstands were later added.
		</p>
		<p>
			Today the Arena holds 5,000 spectators and is used year-round for various events such as the
			Demolition Derby, Draft Horse Show, monster trucks, and more. The complex has an annual
			overall attendance at its various events of more than 211,000.
		</p>
		<p>
			​ In January 2020, the The Kitsap Fair and Stampede Association was formed to take over the
			responsibility of producing the annual Kitsap Fair and Rodeo. The non-profit organization is
			governed by 11 appointed board members. They come with a variety of experience in business,
			public service and public involvement.
		</p>
		<p>
			Unfortunately, the 2020 fair was cancelled due to the COVID-19 virus. In 2023, the Fair and
			Rodeo celebrated the 100th Kitsap Fair. ​In 2024, the Kitsap Stampede celebrated 75 years of
			rodeo in the county.
		</p>
	</section>

	<section>
		<h2>MISSION STATEMENT:</h2>
		<p>
